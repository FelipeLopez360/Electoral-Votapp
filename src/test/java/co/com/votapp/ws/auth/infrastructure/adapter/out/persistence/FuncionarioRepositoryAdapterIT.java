package co.com.votapp.ws.auth.infrastructure.adapter.out.persistence;

import co.com.votapp.ws.TestcontainersDockerConfig;
import co.com.votapp.ws.auth.domain.Funcionario;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.testcontainers.containers.GenericContainer;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Integration test for {@link FuncionarioRepositoryAdapter}.
 *
 * <p>Uses a real PostgreSQL instance via Testcontainers to verify that
 * the adapter correctly persists and queries {@link Funcionario} objects.
 */
@SpringBootTest
@Testcontainers
@DisplayName("FuncionarioRepositoryAdapter - Integration tests with real PostgreSQL")
class FuncionarioRepositoryAdapterIT {

    static {
        TestcontainersDockerConfig.configure();
    }

    @Container
    private static final PostgreSQLContainer<?> postgres = new PostgreSQLContainer<>("postgres:16-alpine")
            .withDatabaseName("votapp_test")
            .withUsername("postgres")
            .withPassword("votapp_password");

    @Container
    private static final GenericContainer<?> redis = new GenericContainer<>("redis:7-alpine")
            .withExposedPorts(6379);

    @DynamicPropertySource
    static void datasourceProperties(DynamicPropertyRegistry registry) {
        registry.add("spring.datasource.url", postgres::getJdbcUrl);
        registry.add("spring.datasource.username", postgres::getUsername);
        registry.add("spring.datasource.password", postgres::getPassword);
        registry.add("spring.redis.host", redis::getHost);
        registry.add("spring.redis.port", () -> redis.getMappedPort(6379));
    }

    @Autowired
    private FuncionarioRepositoryAdapter adapter;

    // ─── Helper ───────────────────────────────────────────────────────────────

    /**
     * Builds a transient Funcionario (no id) with a unique documento and numero_empleado
     * to avoid constraint violations.
     */
    private Funcionario buildFuncionario(String documento, String nombres, String apellidos) {
        // numero_empleado is NOT NULL UNIQUE in the DB schema; generate a unique value per call
        String empNum = "TEST-" + System.nanoTime();
        return new Funcionario(
                null,          // id — generated by DB
                empNum,        // numeroEmpleado — unique per test invocation
                documento,
                nombres,
                apellidos,
                "CC",
                nombres.toLowerCase().replace(" ", ".") + "@test.com",
                null,
                null,
                null,
                null,
                true,
                "ACTIVO",
                true
        );
    }

    // ─── Tests ────────────────────────────────────────────────────────────────

    @Test
    @DisplayName("Should save a new funcionario and find it by id")
    void shouldSaveAndFindFuncionario() {
        // Given
        String documento = "IT-DOC-" + System.nanoTime();
        Funcionario funcionario = buildFuncionario(documento, "Pedro", "Romero");

        // When
        Funcionario saved = adapter.saveWithHash(funcionario, "$2a$10$test-hash");

        // Then
        assertThat(saved.getId()).isNotNull();

        Optional<Funcionario> found = adapter.findById(saved.getId());
        assertThat(found).isPresent();
        assertThat(found.get().getDocumentoIdentidad()).isEqualTo(documento);
        assertThat(found.get().getNombres()).isEqualTo("Pedro");
        assertThat(found.get().getApellidos()).isEqualTo("Romero");
        assertThat(found.get().isPuedeVotar()).isTrue();
        assertThat(found.get().getEstadoLaboral()).isEqualTo("ACTIVO");
        assertThat(found.get().isDebeCambiarPassword()).isTrue();
    }

    @Test
    @DisplayName("Should find funcionarios matching a partial search term")
    void shouldFindBySearchTerm() {
        // Given — two distinct funcionarios
        String suffix = String.valueOf(System.nanoTime());
        Funcionario alvarez = buildFuncionario("SRCH-A-" + suffix, "Mario", "Álvarez" + suffix);
        Funcionario torres = buildFuncionario("SRCH-T-" + suffix, "Sofia", "Torres" + suffix);

        adapter.saveWithHash(alvarez, "$2a$10$hash-a");
        adapter.saveWithHash(torres, "$2a$10$hash-t");

        // When — search by the unique suffix in apellidos
        List<Funcionario> results = adapter.findAll("Álvarez" + suffix);

        // Then — only Álvarez returned
        assertThat(results).isNotEmpty();
        assertThat(results).allSatisfy(f ->
                assertThat(f.getApellidos()).contains("Álvarez" + suffix));
    }

    @Test
    @DisplayName("Should return all funcionarios when search is null or empty")
    void shouldReturnAllWhenSearchIsNull() {
        // Given — at least two funcionarios already exist in the DB (seed data)
        // We just verify that findAll(null) returns a non-empty list
        List<Funcionario> withNull = adapter.findAll(null);
        List<Funcionario> withEmpty = adapter.findAll("");

        // Then
        assertThat(withNull).isNotEmpty();
        assertThat(withEmpty).isNotEmpty();
        assertThat(withNull.size()).isEqualTo(withEmpty.size());
    }

    @Test
    @DisplayName("Should return true when documento already exists, false otherwise")
    void shouldCheckExistsByDocumentoIdentidad() {
        // Given
        String documento = "EXIST-CHK-" + System.nanoTime();
        Funcionario funcionario = buildFuncionario(documento, "Laura", "Gómez");
        adapter.saveWithHash(funcionario, "$2a$10$hash-l");

        // When & Then
        assertThat(adapter.existsByDocumentoIdentidad(documento)).isTrue();
        assertThat(adapter.existsByDocumentoIdentidad("DOES-NOT-EXIST-9999")).isFalse();
    }

    @Test
    @DisplayName("Should persist debeCambiarPassword=false when admin clears the flag via save()")
    void shouldPersistDebeCambiarPasswordFalseAfterUpdate() {
        // Given — create a funcionario with debeCambiarPassword=true (default for new creates)
        String documento = "PWD-FLAG-" + System.nanoTime();
        Funcionario initial = buildFuncionario(documento, "Carlos", "Méndez"); // debeCambiarPassword=true
        Funcionario saved = adapter.saveWithHash(initial, "$2a$10$test-hash-pwd");
        assertThat(saved.isDebeCambiarPassword()).isTrue();

        // When — build an updated domain object with debeCambiarPassword=false and save
        Funcionario withFlagCleared = new Funcionario(
                saved.getId(),
                saved.getNumeroEmpleado(),
                saved.getDocumentoIdentidad(),
                saved.getNombres(),
                saved.getApellidos(),
                saved.getTipoDocumento(),
                saved.getEmail(),
                saved.getTelefono(),
                saved.getDepartamentoId(),
                saved.getCargoId(),
                saved.getFechaIngreso(),
                saved.isPuedeVotar(),
                saved.getEstadoLaboral(),
                false  // debeCambiarPassword cleared by admin
        );
        Funcionario afterUpdate = adapter.save(withFlagCleared);

        // Then — the returned object reflects the change
        assertThat(afterUpdate.isDebeCambiarPassword()).isFalse();

        // And — reading back from DB confirms the value is persisted, not just in memory
        Funcionario reloaded = adapter.findById(saved.getId())
                .orElseThrow(() -> new AssertionError("Funcionario not found after update"));
        assertThat(reloaded.isDebeCambiarPassword())
                .as("debeCambiarPassword must be persisted as false in the database")
                .isFalse();
    }
}
